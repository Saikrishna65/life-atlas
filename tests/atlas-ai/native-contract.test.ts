import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {test} from 'node:test';
test('native voice contract has no generic recognizer, online voice fallback or automatic model download',()=>{
 const source=readFileSync('android/app/src/main/java/com/lifeatlas/app/AtlasLocalAIPlugin.java','utf8');
 assert.ok(source.includes('createOnDeviceSpeechRecognizer'));
 assert.ok(!source.includes('SpeechRecognizer.createSpeechRecognizer('));
 assert.ok(source.includes('!voice.isNetworkConnectionRequired()'));
 assert.ok(source.includes('pendingPermissionEpoch'));
 assert.ok(source.includes('AUDIO_BECOMING_NOISY'));
 assert.ok(source.includes('handleOnPause()'));
 assert.ok(source.includes('call.resolve(inference.status())'));
 const controller=readFileSync('android/app/src/main/java/com/lifeatlas/app/AtlasInferenceController.java','utf8');
 assert.ok(controller.includes('if (!AtlasLlamaNative.available()) return status(false'));
 assert.ok(controller.includes('AtlasVerifiedModel.selected(context)'));
 assert.ok(controller.includes('model.verify(r.canceled)'));
 assert.ok(controller.includes('AtlasLlamaNative.generate('));
 assert.ok(!controller.includes('HttpURLConnection'));
 assert.ok(source.includes('keyguard.isDeviceLocked()'));
 assert.ok(source.includes('inference.cancel(null)'));
 const installer=readFileSync('android/app/src/main/java/com/lifeatlas/app/AtlasModelsPlugin.java','utf8');
 assert.ok(installer.includes('call.getBoolean("consent")'));
 assert.ok(installer.includes('if(!AtlasLlamaNative.available())throw'));
 assert.ok(installer.includes('call.getString("acceptedLicense","")'));
 assert.ok(installer.includes('call.getString("acceptedRevision","")'));
 assert.ok(!source.includes('HttpURLConnection'));
 const bridge=readFileSync('src/lib/atlas-ai/native.ts','utf8');
 assert.ok(bridge.includes("isPluginAvailable('BiometricAuthNative')"));
 assert.ok(!bridge.includes('authenticateWithDevice'));
});
