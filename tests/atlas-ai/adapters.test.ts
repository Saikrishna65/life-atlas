import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import {test} from 'node:test';
import {createLocalAdapters, type LocalPlayback} from '@/lib/atlas-ai/local-adapters';
import {ActionGateway, type Permission} from '@/lib/atlas-ai/gateway';
import {saveTrack,getTrack} from '@/lib/music/storage';
import {saveTrip,saveItineraryDay,getItinerariesForTrip} from '@/lib/vault/storage';
import {AccountService} from '@/lib/finance/application/accountService';
import {IndexedDBUnitOfWork} from '@/lib/finance/storage/indexeddb/unitOfWork';
Object.defineProperty(globalThis,'window',{configurable:true,value:new EventTarget()});
test('real local adapters read data and use existing services only after request-bound confirmation', async()=>{
 const at='2026-11-06T00:00:00Z', uow=new IndexedDBUnitOfWork();
 const account=await new AccountService(uow).createAccount({name:'Synthetic cash',accountType:'cash',openingBalancePaise:10000});
 await saveTrip({id:'atlas-test-trip',title:'Synthetic hills',destination:'Hills',status:'PLANNING',startDate:at,endDate:at,travelStyle:'LEISURE',budgetTotal:1000,currency:'INR',createdAt:at,updatedAt:at});
 await saveItineraryDay({id:'atlas-test-day',tripId:'atlas-test-trip',dayIndex:1,date:at,title:'Original day',activities:[],createdAt:at,updatedAt:at});
 await saveTrack({id:'atlas-test-song',title:'Synthetic song',artist:'Test',album:'',genre:'',duration:1,size:3000,format:'audio/mpeg',audioBlob:new Blob([new Uint8Array(3000)]),source:'IMPORTED',isFavorite:false,playCount:0,addedAt:1});
 let played='', paused=false, resumed=false, opened='';
 const local=(await getTrack('atlas-test-song'))!;
 const player: LocalPlayback={currentTrack:local,isPlaying:false,queue:[local,{...local,id:'cloud-only',audioBlob:undefined},{...local,id:'next-local'}],queueIndex:0,playTrack:async t=>{played=t.id;},pause:()=>{paused=true;},resume:()=>{resumed=true;},nextTrack:()=>{throw new Error('Unsafe unfiltered next');}};
 const adapter=createLocalAdapters(()=>player,href=>{opened=href;});
 const grants=new Set<Permission>(['music.read','music.control','finance.read','finance.write','trips.read','trips.write','navigate']);
 const g=new ActionGateway(adapter,()=>grants,async()=>{});
 assert.equal(((await g.request('session',{kind:'music.search',query:'Synthetic'})).result as unknown[]).length,1);
 await g.request('session',{kind:'music.play',id:local.id}); assert.equal(played,local.id);
 await g.request('session',{kind:'music.pause'}); assert.equal(paused,true);
 await g.request('session',{kind:'music.resume'}); assert.equal(resumed,true);
 await g.request('session',{kind:'music.next'}); assert.equal(played,'next-local');
 assert.equal(((await g.request('session',{kind:'trips.search',query:'hills'})).result as unknown[]).length,1);
 const expense=await g.request('session',{kind:'finance.expense',accountId:account.id,amountPaise:500,description:'Synthetic lunch'});
 assert.equal((await uow.transactions.query({})).length,0);
 const receipt=await g.confirm('session',expense.proposal!.token);
 assert.ok(receipt.id); assert.equal((await uow.accounts.getById(account.id))!.currentBalancePaise,9500);
 const summary=(await g.request('session',{kind:'finance.summary'})).result as {accounts:unknown[];transactions:unknown[]};
 assert.equal(summary.accounts.length,1); assert.equal(summary.transactions.length,1);
 const transaction=(await uow.transactions.query({}))[0];
 const category=(await uow.categories.getAll()).find(c=>c.type==='expense'&&c.id!==transaction.categoryId)!;
 const categorization=await g.request('session',{kind:'finance.categorize',id:transaction.id,categoryId:category.id});
 assert.notEqual((await uow.transactions.getById(transaction.id))!.categoryId,category.id);
 await g.confirm('session',categorization.proposal!.token);
 assert.equal((await uow.transactions.getById(transaction.id))!.categoryId,category.id);
 assert.equal((await uow.accounts.getById(account.id))!.currentBalancePaise,9500);
 const staleExpense=await g.request('session',{kind:'finance.expense',accountId:account.id,amountPaise:100,description:'Stale synthetic expense'});
 await uow.accounts.save({...((await uow.accounts.getById(account.id))!),name:'Edited account'});
 await assert.rejects(()=>g.confirm('session',staleExpense.proposal!.token),/Account changed/);
 assert.equal((await uow.transactions.query({})).length,1);

 const edit=await g.request('session',{kind:'trips.editTitle',tripId:'atlas-test-trip',dayId:'atlas-test-day',title:'Confirmed day'});
 assert.equal((await getItinerariesForTrip('atlas-test-trip'))[0].title,'Original day');
 await g.confirm('session',edit.proposal!.token);
 assert.equal((await getItinerariesForTrip('atlas-test-trip'))[0].title,'Confirmed day');
 const stale=await g.request('session',{kind:'trips.editTitle',tripId:'atlas-test-trip',dayId:'atlas-test-day',title:'Stale edit'});
 await saveItineraryDay({...((await getItinerariesForTrip('atlas-test-trip'))[0]),title:'Newer user edit'});
 await assert.rejects(()=>g.confirm('session',stale.proposal!.token),/changed/);
 assert.equal((await getItinerariesForTrip('atlas-test-trip'))[0].title,'Newer user edit');
 await g.request('session',{kind:'trips.open',id:'atlas-test-trip'});
 assert.equal(opened,'/secret/vault/atlas-test-trip/itinerary');
});
