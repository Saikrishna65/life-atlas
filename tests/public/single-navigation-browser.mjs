import{createRequire}from'node:module';
import{readFile,mkdir}from'node:fs/promises';
import assert from'node:assert/strict';
const{chromium}=createRequire(import.meta.url)('playwright');
const b=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--enable-unsafe-swiftshader']});
const errors=[];
await mkdir('work/qa-single-nav',{recursive:true});

try{for(const mobile of[false,true]){const p=await b.newPage({viewport:mobile?{width:390,height:844}:{width:1920,height:1080},isMobile:mobile,hasTouch:mobile,reducedMotion:'reduce'});
p.on('pageerror',e=>errors.push(e.message));
await p.route('https://videos.pexels.com/**',async r=>r.fulfill({contentType:'video/mp4',body:await readFile('public/films/hero/highlands.mp4')}));
await p.goto('http://localhost:3008');
const nav=p.getByRole('navigation',{name:'World chapters',exact:true});
await nav.waitFor();
assert.equal(await p.locator('.trip-film-header,.trip-film-navigation').count(),0);
await nav.evaluate(el=>el.dataset.retained='yes');
assert.ok((await nav.locator('img').getAttribute('src')).includes('life-atlas-white'));
await p.getByRole('button',{name:'Play trip films',exact:true}).click();
await p.waitForFunction(()=>document.querySelector('video[data-showing="true"]')?.paused===false);
await nav.getByRole('button',{name:'The atlas',exact:true}).click();
await p.getByRole('dialog').waitFor();
await p.waitForFunction(()=>document.querySelector('video[data-showing="true"]')?.paused===true);
await p.keyboard.press('Escape');
await p.getByRole('dialog').waitFor({state:'hidden'});
await p.screenshot({path:`work/qa-single-nav/hero-${mobile?'mobile':'desktop'}.png`});
await nav.getByRole('button',{name:'The atlas',exact:true}).click();
await p.locator('.world-chapter-menu button').filter({hasText:'The Observatory'}).click();
await p.waitForFunction(()=>Math.abs(document.querySelector('#observatory')?.getBoundingClientRect().top)<12);
assert.equal(await nav.getAttribute('data-retained'),'yes');
assert.equal(await p.locator('nav[aria-label="World chapters"]').count(),1);
assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await p.screenshot({path:`work/qa-single-nav/globe-${mobile?'mobile':'desktop'}.png`});
await p.goto('http://localhost:3008/map');
await p.locator('.public-header').waitFor();
assert.ok((await p.locator('.public-header img').getAttribute('src')).includes('life-atlas-white'));
assert.equal(await p.locator('img[src*="life-atlas-black"]').count(),0);
await p.close();
}assert.deepEqual(errors,[]);
console.log('PASS single retained navbar through hero/globe, white logos on public routes, functional menu and video controls, menu pauses playback, desktop/mobile without overflow or browser exceptions. Local video fixtures.');
}finally{await b.close();
}
