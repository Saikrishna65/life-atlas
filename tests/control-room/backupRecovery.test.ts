import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import {test} from 'node:test';
import type {FinanceAccount} from '@/lib/finance/domain/models';
import {IndexedDBUnitOfWork,AccountService} from '@/lib/finance';
import {snapshotVault} from '@/lib/control-room/local';
import {validateBackup,normalizeRestoreSnapshots,previewRestore,restoreBackup,encryptPayload,decryptArchive,type BackupPayload} from '@/lib/control-room/backup';
Object.defineProperty(globalThis,'window',{configurable:true,value:new EventTarget()});
test('validation and preview preserve input and persisted balances; manual restore normalizes a copy',async()=>{
 const uow=new IndexedDBUnitOfWork();
 const account=await new AccountService(uow).createAccount({name:'Synthetic bank',accountType:'bank',openingBalancePaise:12300});
 const vault=await snapshotVault('finance');
 const row=vault.stores.find(s=>s.name==='accounts')!.rows.find(r=>r.key===account.id)!;
 (row.value as FinanceAccount).currentBalancePaise=999;
 const payload:BackupPayload={format:'life-atlas-v1',createdAt:new Date().toISOString(),media:true,vaults:[vault]};
 const before=structuredClone(payload);
 Object.freeze(row.value);
 await validateBackup(payload);
 const plan=await previewRestore(payload);
 assert.deepEqual(payload,before);
 assert.equal(((await snapshotVault('finance')).stores.find(s=>s.name==='accounts')!.rows.find(r=>r.key===account.id)!.value as FinanceAccount).currentBalancePaise,12300);
 const normalized=normalizeRestoreSnapshots([vault]);
 assert.equal((normalized[0].stores.find(s=>s.name==='accounts')!.rows.find(r=>r.key===account.id)!.value as FinanceAccount).currentBalancePaise,12300);
 assert.deepEqual(payload,before);
 const decoded=await decryptArchive(await encryptPayload(payload,'synthetic-passphrase'),'synthetic-passphrase');
 assert.equal((decoded.vaults[0].stores.find(s=>s.name==='accounts')!.rows.find(r=>r.key===account.id)!.value as FinanceAccount).currentBalancePaise,999);
 await restoreBackup(payload,'synthetic-passphrase',plan.fingerprint);
 assert.equal(((await snapshotVault('finance')).stores.find(s=>s.name==='accounts')!.rows.find(r=>r.key===account.id)!.value as FinanceAccount).currentBalancePaise,12300);
 assert.deepEqual(payload,before);
 await assert.rejects(()=>validateBackup({...payload,media:undefined} as unknown as BackupPayload),/metadata/);
 await assert.rejects(()=>validateBackup({...payload,vaults:[{...vault,version:NaN}]}),/newer version/);
});
